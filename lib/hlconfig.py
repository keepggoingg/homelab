"""Homelab configuration: config/homelab.env (infra + secrets) and config/settings.json (dashboard).

Both files are gitignored. config/homelab.env.example documents every key:
  # Help text for the key (one or more comment lines right above it)
  # secret        <- marks the key as a secret: never sent back to the browser
  KEY=default
"""
import json, os, re, string, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "config"
ENV_FILE = CONFIG / "homelab.env"
ENV_EXAMPLE = CONFIG / "homelab.env.example"
SETTINGS_FILE = CONFIG / "settings.json"
PUBLIC_ENV = CONFIG / "public.env"   # non-secret keys only, for systemd EnvironmentFile=
KEY_RE = re.compile(r"^([A-Z][A-Z0-9_]*)=(.*)$")

DASHBOARD_DEFAULTS = {
    "location_name": "Home",
    "latitude": 51.5074,
    "longitude": -0.1278,
    "timezone": "",            # empty = TZ from homelab.env
    "probe_url": "",           # empty = https://$DOMAIN
    "probe_label": "",         # empty = $DOMAIN
}


def _unquote(v):
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] == "'":
        return v[1:-1]
    if len(v) >= 2 and v[0] == v[-1] == '"':
        return re.sub(r'\\(["\\])', r"\1", v[1:-1])
    return v


def _quote(v):
    v = str(v)
    if v == "" or re.fullmatch(r"[A-Za-z0-9_./:@,+-]+", v):
        return v
    return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'


def read_env(path=ENV_FILE):
    env = {}
    if path.exists():
        for line in path.read_text().splitlines():
            m = KEY_RE.match(line.strip())
            if m:
                env[m.group(1)] = _unquote(m.group(2))
    return env


def schema():
    """Keys documented in the example file, in order: [{key, default, help, secret}]."""
    out, comments = [], []
    for line in ENV_EXAMPLE.read_text().splitlines():
        s = line.strip()
        if s.startswith("#"):
            comments.append(s.lstrip("#").strip())
            continue
        m = KEY_RE.match(s)
        if m:
            secret = "secret" in comments
            help_ = " ".join(c for c in comments if c and c != "secret")
            out.append({"key": m.group(1), "default": _unquote(m.group(2)), "help": help_, "secret": secret})
        comments = []
    return out


def secret_keys():
    return {k["key"] for k in schema() if k["secret"]}


def _atomic_write(path, text, mode=0o600):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix="." + path.name)
    with os.fdopen(fd, "w") as f:
        f.write(text)
    os.chmod(tmp, mode)
    os.replace(tmp, path)


def write_env(updates, path=ENV_FILE):
    """Set keys in homelab.env, keeping comments, order and keys we don't know about."""
    for k, v in updates.items():
        if not KEY_RE.match(f"{k}=x"):
            raise ValueError(f"bad key {k!r}")
        if "\n" in str(v) or "\r" in str(v):
            raise ValueError(f"{k}: value must be one line")
    lines = path.read_text().splitlines() if path.exists() else []
    left = dict(updates)
    for i, line in enumerate(lines):
        m = KEY_RE.match(line.strip())
        if m and m.group(1) in left:
            lines[i] = f"{m.group(1)}={_quote(left.pop(m.group(1)))}"
    lines += [f"{k}={_quote(v)}" for k, v in left.items()]
    _atomic_write(path, "\n".join(lines) + "\n")


def read_settings():
    s = dict(DASHBOARD_DEFAULTS)
    if SETTINGS_FILE.exists():
        s.update({k: v for k, v in json.loads(SETTINGS_FILE.read_text()).items() if k in DASHBOARD_DEFAULTS})
    return s


def write_settings(updates):
    s = read_settings()
    for k, v in updates.items():
        if k not in DASHBOARD_DEFAULTS:
            raise ValueError(f"unknown setting {k!r}")
        if isinstance(DASHBOARD_DEFAULTS[k], float):
            v = float(v)
        s[k] = v
    _atomic_write(SETTINGS_FILE, json.dumps(s, indent=2) + "\n", 0o644)
    return s


def dashboard_config():
    """What the kiosk page needs (no secrets)."""
    env, s = read_env(), read_settings()
    domain = env.get("DOMAIN", "")
    return dict(s, timezone=s["timezone"] or env.get("TZ", ""), host=env.get("HL_HOST", ""),
                probe_url=s["probe_url"] or (f"https://{domain}/" if domain else ""),
                probe_label=s["probe_label"] or domain)


def write_public_env(env=None):
    env = env if env is not None else read_env()
    hidden = secret_keys()
    text = "# Generated by bin/homelab render from homelab.env: non-secret keys only.\n" + \
        "".join(f"{k}={_quote(v)}\n" for k, v in env.items() if k not in hidden)
    changed = not PUBLIC_ENV.exists() or PUBLIC_ENV.read_text() != text
    if changed:
        _atomic_write(PUBLIC_ENV, text, 0o644)
    return changed


def render(template, out, env=None):
    """Fill ${VAR} in a template file; fail on missing keys so half-rendered configs never land."""
    env = env if env is not None else read_env()
    text = string.Template(Path(template).read_text()).substitute(env)
    changed = not Path(out).exists() or Path(out).read_text() != text
    if changed:
        _atomic_write(Path(out), text, 0o644)
    return changed
